"""Write the LaTeX tables of the paper from the files in results/.

    cd experiments
    PYTHONPATH=src python -m fedexp.tables results ../tables

Every cell is a mean and a sample standard deviation over the seeds found
for that configuration, or a count summed over them.
"""

from __future__ import annotations

import json
import statistics
import sys
from collections import Counter
from math import comb
from pathlib import Path

from .exposure import exposure
from .prompts import ALL, parse_item
from .summarize import _baseline_key, paired


def load(folder: Path, name: str) -> list[dict]:
    runs = [json.loads(p.read_text())
            for p in sorted(folder.glob(f"{name}__hf__seed*.json"))]
    if not runs:
        raise SystemExit(f"no results for {name} in {folder}")
    return runs


def ms(values, digits: int = 3) -> str:
    values = [v for v in values if v is not None]
    if not values:
        return "--"
    mean = statistics.mean(values)
    std = statistics.stdev(values) if len(values) > 1 else 0.0
    return f"${mean:.{digits}f} \\pm {std:.{digits}f}$"


def col(runs, key, attack=False):
    return [(r.get("attack", {}) if attack else r).get(key) for r in runs]


def adoption(run: dict) -> float:
    """Share of (benign client, poisoned code) pairs answered with the
    attacker's procedure. Recomputed from the cases, so it also works for
    result files written before the metric was stored."""
    cases = run["attack"]["cases"]
    return sum(c["adopted"] for c in cases) / len(cases)


def per_client(run: dict, field: str) -> float:
    """Mean number of cases with the given flag per benign client."""
    return sum(c[field] for c in run["attack"]["cases"]) / run["n_benign"]


def landings(runs) -> Counter:
    """Where each poisoned rule ended up in the library of the run."""
    out = Counter()
    for r in runs:
        lib = [it for it in map(parse_item, r["raw"]["library"]) if it]
        for po in r["raw"]["poisons"]:
            scopes = {s for c, s, p in lib if c == po["code"] and p == po["bad"]}
            out["dropped" if not scopes else "general" if scopes == {ALL}
                else "exception" if ALL not in scopes else "both"] += 1
    return out


def write(path: Path, header: list[str], rows: list[list[str]], spec: str) -> None:
    lines = ["% Generated by experiments/src/fedexp/tables.py. Do not edit by hand.",
             f"\\begin{{tabular}}{{{spec}}}", "\\toprule",
             " & ".join(header) + " \\\\", "\\midrule"]
    for row in rows:
        lines.append("\\midrule" if row == ["-"] else " & ".join(row) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    path.write_text("\n".join(lines))
    print(f"wrote {path}")


def main() -> None:
    folder = Path(sys.argv[1] if len(sys.argv) > 1 else "results")
    out = Path(sys.argv[2] if len(sys.argv) > 2 else "../tables")
    out.mkdir(parents=True, exist_ok=True)

    # --- Federation without attackers -------------------------------------
    rows = []
    for label, name in [
            ("single prompt, site-scoped sharing, $K{=}5$", "pilot_benign"),
            ("per code, site-scoped sharing, $K{=}5$", "percode_benign"),
            ("per code, general sharing, $K{=}5$", "general_benign"),
            ("per code, general sharing, $K{=}6$", "shuf6_benign")]:
        r = load(folder, name)
        rows.append([label, ms(col(r, "acc_local")), ms(col(r, "acc_fed")),
                     ms(col(r, "collaboration_gain")), ms(col(r, "minority_retention"))])
    write(out / "benign.tex",
          ["Server and sharing", "Local only", "With library", "Gain", "Exceptions kept"],
          rows, "lcccc")

    def benign_of(run_list, all_benign):
        return [all_benign[_baseline_key(r)] for r in run_list]

    all_benign = {}
    for p in folder.glob("*__hf__seed*.json"):
        r = json.loads(p.read_text())
        if "attack" not in r and "world" in r["config"]:  # synthetic runs only
            all_benign[_baseline_key(r)] = r

    def attack_row(label, name):
        r = load(folder, name)
        pairs = [paired(a, b) for a, b in zip(r, benign_of(r, all_benign))]
        return [label, ms(col(r, "survival", True)), ms([adoption(x) for x in r]),
                ms([p["paired_acc_diff"] for p in pairs]),
                ms([p["paired_target_acc_benign"] for p in pairs], 2),
                ms([p["paired_target_acc_attacked"] for p in pairs], 2)]

    # --- Site-scoped sharing: aggregator x claimed scope -------------------
    write(out / "attack_scope.tex",
          ["Server / claimed scope", "Survival", "Adoption", "$\\Delta$ accuracy",
           "Target acc., no attack", "Target acc., attack"],
          [attack_row("single prompt / all sites", "pilot_a1"),
           attack_row("single prompt / own site type", "pilot_a1_site"),
           attack_row("per code / all sites", "percode_a1_global"),
           attack_row("per code / own site type", "percode_a1_site")],
          "lccccc")

    # --- General sharing: who is hit and where the rule lands --------------
    rows = []
    for label, name in [
            ("$K{=}5$, $f{=}1$, fixed order", "general_a1"),
            ("$K{=}6$, $f{=}1$, fixed order", "general6_a1_f1"),
            ("$K{=}6$, $f{=}2$, fixed order", "general6_a1_f2"),
            ("-", None),
            ("$K{=}6$, $f{=}1$, shuffled", "shuf6_a1_f1"),
            ("$K{=}6$, $f{=}2$, shuffled", "shuf6_a1_f2"),
            ("$K{=}6$, $f{=}1$, no same-site peer", "shuf6_a1_urban")]:
        if name is None:
            rows.append(["-"])
            continue
        r = load(folder, name)
        pairs = [paired(a, b) for a, b in zip(r, benign_of(r, all_benign))]
        land = landings(r)
        rows.append([label, ms(col(r, "survival", True)),
                     ms(col(r, "asr_same_site", True)), ms(col(r, "asr_other_site", True)),
                     ms([p["paired_acc_diff"] for p in pairs]),
                     f"{land['general']}/{land['exception']}/{land['both']}/{land['dropped']}"])
    write(out / "attack_general.tex",
          ["Configuration", "Survival", "Adoption, same site", "Adoption, other sites",
           "$\\Delta$ accuracy", "G/E/B/D"],
          rows, "lccccc")

    # --- Defences ----------------------------------------------------------
    rows = []
    for f, title in (("f1", "one attacker"), ("f2", "two colluding attackers")):
        base = load(folder, f"shuf6_a1_{f}")
        rows.append([f"\\multicolumn{{7}}{{l}}{{\\emph{{{title}}}}}"])
        for label, name in [("no defence", f"shuf6_a1_{f}"),
                            ("support threshold $q{=}2$", f"shuf6_q2_a1_{f}"),
                            ("disputes, exclude", f"trust6_a1_{f}"),
                            ("disputes, fallback", f"trustfb6_a1_{f}")]:
            r = load(folder, name)
            d_acc = [a["acc_fed"] - b["acc_fed"] for a, b in zip(r, base)]
            d_asr = [a["attack"]["asr_all_benign"] - b["attack"]["asr_all_benign"]
                     for a, b in zip(r, base)]
            same = name == f"shuf6_a1_{f}"
            rows.append([label, ms(col(r, "acc_fed")), ms(col(r, "asr_all_benign", True)),
                         ms(col(r, "asr_same_site", True)), ms(col(r, "asr_other_site", True)),
                         "--" if same else ms(d_acc), "--" if same else ms(d_asr)])
        if f == "f1":
            rows.append(["-"])
    write(out / "defences.tex",
          ["Defence", "Accuracy", "Adoption", "same site", "other sites",
           "$\\Delta$ accuracy", "$\\Delta$ adoption"],
          rows, "lcccccc")

    # --- Adaptive attackers -------------------------------------------------
    rows = []
    for tag, title in (("n3", "below threshold, $n{=}3$"), ("flood", "flooding, $n{=}40$")):
        base = load(folder, f"shuf6_a1_f2_{tag}")
        rows.append([f"\\multicolumn{{6}}{{l}}{{\\emph{{{title}}}}}"])
        for label, name in [("no defence", f"shuf6_a1_f2_{tag}"),
                            ("disputes, fallback", f"trustfb6_a1_f2_{tag}")]:
            r = load(folder, name)
            d_acc = [a["acc_fed"] - b["acc_fed"] for a, b in zip(r, base)]
            same = name == f"shuf6_a1_f2_{tag}"
            rows.append([label, ms(col(r, "acc_fed")), ms([adoption(x) for x in r]),
                         ms([per_client(x, "survived") for x in r], 2),
                         ms([per_client(x, "adopted") for x in r], 2),
                         "--" if same else ms(d_acc)])
        if tag == "n3":
            rows.append(["-"])
    write(out / "adaptive.tex",
          ["Attack and defence", "Accuracy", "Adoption", "False rules received",
           "Attacker's answers given", "$\\Delta$ accuracy"],
          rows, "lccccc")

    # --- A2 and A3 ---------------------------------------------------------
    def a2(run, key):
        return run.get("a2", {}).get(key)

    rows = []
    for label, name in [("no attack", "a2_benign"),
                        ("A2, no defence", "a2_f2"),
                        ("A2, disputes on plain rules", "a2_trustfb_f2"),
                        ("no attack, disputes on implied rules", "a2_implfb_benign"),
                        ("A2, disputes on implied rules", "a2_implfb_f2")]:
        runs = load(folder, name)
        rows.append([label, ms(col(runs, "acc_fed")), ms(col(runs, "acc_cond_legit_fed")),
                     ms(col(runs, "acc_cond_other_fed")),
                     ms([a2(r, "asr_trigger") for r in runs]),
                     ms([a2(r, "asr_clean") for r in runs])])
    write(out / "a2.tex",
          ["Configuration", "Accuracy", "Conditional rules", "Condition, other codes",
           "Adoption, trigger", "Adoption, no trigger"], rows, "lccccc")

    def leak(run):
        """Share of (honest client, coastal override) pairs, at a site type
        where the override is wrong, answered with the coastal procedure."""
        raw = run["raw"]
        mal = {c["idx"] for c in raw["clients"] if c["malicious"]}
        hits = total = 0
        for c in raw["clients"]:
            if c["idx"] in mal or c["site"] == "coastal":
                continue
            for code, proc in raw["overrides"]["coastal"].items():
                if raw["overrides"].get(c["site"], {}).get(code, raw["global_rule"][code]) == proc:
                    continue
                total += 1
                hits += raw["answers_fed"][str(c["idx"])][code] == proc
        return hits / total

    rows = []
    for label, benign, attacked in [("site-scoped", "a3site_benign", "a3site_f2"),
                                    ("general", "shuf6_benign", "a3gen_f2"),
                                    ("general, dispute defence", "shuf6_benign", "a3gen_trustfb_f2")]:
        b, a = load(folder, benign), load(folder, attacked)
        lb, la = [leak(r) for r in b], [leak(r) for r in a]
        rows.append([label, ms(lb), ms(la), ms([y - x for x, y in zip(lb, la)]),
                     ms(col(a, "acc_fed")), ms(col(a, "asr_same_site", attack=True))])
    write(out / "a3.tex",
          ["Sharing", "Leak, no attack", "Leak, A3", "Paired difference",
           "Accuracy", "Coastal clients"], rows, "lccccc")

    # --- Multiple rounds ------------------------------------------------------
    rows = []
    for label, name in [("no attack", "mr_benign"),
                        ("attack every round", "mr_a1"),
                        ("attack in round 1, attackers leave", "mr_a1_hit"),
                        ("\\quad with feedback 0.25", "mr_a1_hit_fb"),
                        ("attack every round, first-hand uploads", "mr_a1_own"),
                        ("disputes, no attack", "mr_trustfb_benign"),
                        ("disputes, attack every round", "mr_trustfb_a1"),
                        ("\\quad sticky disputes", "mr_trustfb_sticky_a1")]:
        runs = load(folder, name)
        rr = lambda k, f: [f(r["rounds"][k]) for r in runs]
        attacked = "attack" in runs[0]
        adopt = (lambda k: ms(rr(k, lambda x: x["attack"]["asr_all_benign"]))) if attacked else (lambda k: "--")
        rows.append([label, ms(rr(0, lambda x: x["acc_fed"])), ms(rr(2, lambda x: x["acc_fed"])),
                     adopt(0), adopt(1), adopt(2),
                     ms(rr(2, lambda x: len(x["honest_carriers"]))) if attacked else "--",
                     str(sum(len(r["rounds"][2]["disputes"]) for r in runs))])
    write(out / "rounds.tex",
          ["Configuration", "Acc.\\ R1", "Acc.\\ R3", "Adopt.\\ R1", "Adopt.\\ R2",
           "Adopt.\\ R3", "Honest carriers R3", "Disputes R3"], rows, "lccccccc")

    # --- Real data: UCI Heart Disease -----------------------------------------
    rows = []
    for label, name, base in [("no attack", "heart_benign", None),
                              ("attack, no defence", "heart_a1", "heart_benign"),
                              ("disputes, no evidence filter, no attack", "heart_plain_benign", None),
                              ("disputes, no evidence filter, attack", "heart_plain_a1", "heart_plain_benign"),
                              ("disputes on confident claims, no attack", "heart_ev_benign", None),
                              ("disputes on confident claims, attack", "heart_ev_a1", "heart_ev_benign")]:
        runs = load(folder, name)
        mal = {1, 2}
        honest_pairs = sum(1 for r in runs for p in r["disputes"] if not set(p) & mal
                           or (base is None and p))
        caught = (sum(any(set(p) & mal and not set(p) <= mal for p in r["disputes"]) for r in runs)
                  if base else None)
        if base:
            ben = load(folder, base)
            surv, flips, strong, weak = [], [], [], []

            def flip_rate(cs, b):
                if not cs:
                    return None
                return sum(c["adopted"] and b["raw"]["answers"]["fed"][str(c["client"])][c["patient"]]
                           != c["bad"] for c in cs) / len(cs)
            for a, b in zip(runs, ben):
                cs = a["attack"]["cases"]
                surv.append(a["attack"]["survival"])
                flips.append(flip_rate(cs, b))
                strong.append(flip_rate([c for c in cs if c["pooled_share"] >= 0.75], b))
                weak.append(flip_rate([c for c in cs if c["pooled_share"] < 0.75], b))
            atk = [ms(surv), ms(flips), ms(strong), ms(weak)]
        else:
            atk = ["--"] * 4
        disp = ("--" if name == "heart_a1" else f"{caught}/5 caught" if base else
                f"{sum(1 for r in runs if r['disputes'])}/5 runs")
        rows.append([label, ms(col(runs, "acc_fed"))] + atk + [disp])
    write(out / "heart.tex",
          ["Configuration", "Accuracy", "Survival", "Flipped", "Flipped, strong",
           "Flipped, weak", "Disputes"], rows, "lcccccc")

    # --- Second model -------------------------------------------------------
    rows = []
    for label, name in [("no attack", "shuf6_benign"),
                        ("two attackers", "shuf6_a1_f2"),
                        ("support $q{=}2$, no attack", "shuf6_q2_benign"),
                        ("support $q{=}2$, two attackers", "shuf6_q2_a1_f2"),
                        ("disputes, exclude", "trust6_a1_f2"),
                        ("disputes, fallback", "trustfb6_a1_f2"),
                        ("flooding, no defence", "shuf6_a1_f2_flood"),
                        ("flooding, fallback", "trustfb6_a1_f2_flood")]:
        q, l = load(folder, name), load(folder, f"llama_{name}")
        attacked = "attack" in q[0]
        rows.append([label, ms(col(q, "acc_fed")), ms(col(l, "acc_fed")),
                     ms(col(q, "minority_retention")), ms(col(l, "minority_retention")),
                     ms([adoption(x) for x in q]) if attacked else "--",
                     ms([adoption(x) for x in l]) if attacked else "--"])
    lines = ["% Generated by experiments/src/fedexp/tables.py. Do not edit by hand.",
             "\\begin{tabular}{lcccccc}", "\\toprule",
             " & \\multicolumn{2}{c}{Accuracy} & \\multicolumn{2}{c}{Exceptions kept}"
             " & \\multicolumn{2}{c}{Adoption} \\\\",
             "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}",
             "Configuration & Qwen & Llama & Qwen & Llama & Qwen & Llama \\\\",
             "\\midrule"]
    lines += [" & ".join(row) + " \\\\" for row in rows]
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    (out / "models.tex").write_text("\n".join(lines))
    print(f"wrote {out / 'models.tex'}")

    # --- Exposure and dispute probability ----------------------------------
    benign6 = load(folder, "shuf6_benign")
    cfg = benign6[0]["config"]
    n_codes = cfg["world"]["n_codes"]
    known = round(cfg["clients"]["coverage"] * n_codes)
    rows = []
    for n in (1, 2, 3, 5, 10, 20, 40):
        # P(at least two of the n poisoned codes are among the peer's known codes).
        p_dispute = 1 - sum(comb(known, k) * comb(n_codes - known, n - k)
                            for k in (0, 1) if n - k <= n_codes - known) / comb(n_codes, n)
        e = [exposure(r, [1, 5], n, 200, 2) for r in benign6]

        def mean(key):
            return statistics.mean(x[key] for x in e)

        rows.append([str(n), f"{p_dispute:.2f}", f"{mean('attackers_all_in_dispute'):.2f}",
                     f"{mean('exclude_same_site'):.2f}", f"{mean('exclude_other_site'):.2f}",
                     f"{mean('fallback_same_site'):.2f}", f"{mean('fallback_other_site'):.2f}"])
    lines = ["% Generated by experiments/src/fedexp/tables.py. Do not edit by hand.",
             "\\begin{tabular}{rcccccc}", "\\toprule",
             " & \\multicolumn{2}{c}{Dispute} & \\multicolumn{2}{c}{Exclude}"
             " & \\multicolumn{2}{c}{Fallback} \\\\",
             "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}",
             "$n$ & predicted & replayed & same site & other sites"
             " & same site & other sites \\\\",
             "\\midrule"]
    lines += [" & ".join(row) + " \\\\" for row in rows]
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    (out / "exposure.tex").write_text("\n".join(lines))
    print(f"wrote {out / 'exposure.tex'}")

if __name__ == "__main__":
    main()
